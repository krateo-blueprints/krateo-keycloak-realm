#!/usr/bin/env python3
"""CI gate for confidential clients (clients[]), on the rendered example examples/openstack-keystone.

- Each client is a confidential KeycloakClient whose clientSecretRef names exactly the Secret its
  ExternalSecret generates (same name, same key), so Keycloak and the relying party share one value.
- The ExternalSecret generates once (refreshInterval "0") and, with its Password generator, carries
  helm.sh/resource-policy: keep: a regenerated value is not re-pushed to Keycloak while the client spec
  is unchanged, so it would silently diverge from the relying party's copy.
- A KeycloakClientConfiguration is rendered even with the portal client disabled.
- Back-channel logout attributes are set when backchannelLogout.url is.
SELF-TEST: a render whose secretRef key differs from the generated key must fail the check.
"""
import shutil, subprocess, sys, tempfile
from pathlib import Path
import yaml

CHART = Path("helm/krateo-keycloak-realm")
EXAMPLE = "examples/openstack-keystone/values.yaml"


def render(extra=()):
    work = Path(tempfile.mkdtemp(prefix="clients-"))
    try:
        dst = work / "c"
        shutil.copytree(CHART, dst)
        cy = dst / "Chart.yaml"
        cy.write_text(cy.read_text().replace("CHART_VERSION", "0.0.0-ci"))
        p = subprocess.run(["helm", "template", "r", str(dst), "-f", EXAMPLE, *extra], capture_output=True, text=True)
        if p.returncode != 0:
            sys.exit(f"::error::render failed: {p.stderr.strip()[:400]}")
        return [d for d in yaml.safe_load_all(p.stdout) if d]
    finally:
        shutil.rmtree(work, ignore_errors=True)


def problems(docs, mutate_key=None):
    errs = []
    clients = [d for d in docs if d["kind"] == "KeycloakClient"]
    es = {d["spec"]["target"]["name"]: d for d in docs if d["kind"] == "ExternalSecret"}
    gens = {d["metadata"]["name"]: d for d in docs if d["kind"] == "Password"}
    if not clients:
        errs.append("the example renders no KeycloakClient")
    for c in clients:
        s = c["spec"]; ref = dict(s.get("clientSecretRef") or {})
        if mutate_key: ref["key"] = mutate_key
        if s.get("publicClient") is not False:
            errs.append(f"{s['clientId']}: must be confidential (publicClient false)")
        e = es.get(ref.get("name"))
        if e is None:
            errs.append(f"{s['clientId']}: clientSecretRef.name {ref.get('name')!r} is not generated by any ExternalSecret")
            continue
        if ref.get("key") not in e["spec"]["target"]["template"]["data"]:
            errs.append(f"{s['clientId']}: clientSecretRef.key {ref.get('key')!r} is not a key the ExternalSecret writes")
        if e["spec"].get("refreshInterval") != "0":
            errs.append(f"{s['clientId']}: the ExternalSecret must generate once (refreshInterval \"0\")")
        gen = e["spec"]["dataFrom"][0]["sourceRef"]["generatorRef"]["name"]
        for obj in (e, gens.get(gen)):
            if obj is None or obj["metadata"].get("annotations", {}).get("helm.sh/resource-policy") != "keep":
                errs.append(f"{s['clientId']}: the ExternalSecret and its Password generator must carry helm.sh/resource-policy: keep")
        a = s.get("attributes", {})
        if "backchannel.logout.url" in a and a.get("backchannel.logout.session.required") != "true":
            errs.append(f"{s['clientId']}: back-channel logout must default to session required")
    if not [d for d in docs if d["kind"] == "KeycloakClientConfiguration"]:
        errs.append("no KeycloakClientConfiguration rendered for clients with the portal client disabled")
    return errs


docs = render()
if not problems(docs, mutate_key="not-the-generated-key"):
    sys.exit("::error::self-test: a mismatched secretRef key passed; the gate is broken")
errs = problems(docs)
for e in errs:
    print(f"::error::{e}")
if errs:
    sys.exit(1)
print("Checked confidential clients: shared generated secret, generate-once + keep, Configuration, back-channel logout.")
